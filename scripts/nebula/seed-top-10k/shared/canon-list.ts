function normaliseTitle(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9 ]+/g, " ").replace(/\s+/g, " ").trim();
}

function normaliseSurname(s: string): string {
  return s.toLowerCase().replace(/[^a-z]+/g, "");
}

const CANON_KEYS = new Set(
  CANON.map((e) => `${normaliseTitle(e.title)}|${normaliseSurname(e.author_surname)}`),
);

export function isCanon(title: string, authorName: string | null): boolean {
  if (!authorName) return false;
  const surnameGuess = authorName.trim().split(/\s+/).pop() ?? "";
  const key = `${normaliseTitle(title)}|${normaliseSurname(surnameGuess)}`;
  return CANON_KEYS.has(key);
}

export const CANON_SIZE = CANON.length;
